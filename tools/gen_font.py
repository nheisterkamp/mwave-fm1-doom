def main():
    out = sys.argv[1]
    rows = []
    for c in range(32, 96):
        g = GLYPHS.get(chr(c), GLYPHS["?"])
        assert len(g) == 7 and all(len(r) == 5 for r in g), chr(c)
        bits = [sum(1 << (4 - i) for i, ch in enumerate(r) if ch == "#") for r in g]
        rows.append("    {" + ", ".join(f"0x{b:02X}" for b in bits) + f"}},   /* {chr(c)!r} */")
    with open(out, "w") as f:
        f.write("/* generated by tools/gen_font.py: 5x7, ASCII 32..95 (lower case prints as upper case) */\n")
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write("static const uint8_t FONT5X7[64][7] = {\n" + "\n".join(rows) + "\n};\n")


if __name__ == "__main__":
    main()
